"""The app's install status, MO2 setup, Play, and its faces and F4SE plugin stages, on a fake MO2 instance.

See: docs/fork/fo4_gui.md#mo2-setup
"""

import sys
from pathlib import Path

from fo4_import.app import mo2_setup as M
from fo4_import.app import runtime_dll
from fo4_import.app import settings as S
from fo4_import.app import stages as ST
from fo4_import.app.runner import Runner
from tools.validate.fo4_install_check import machine_from

HEADER = '# This file was automatically generated by Mod Organizer.'


def _instance(tmp_path: Path, executables: bool = True) -> Path:
    """An MO2 instance with profile Play (selected), an F4SE executable, and lists holding one mod and plugin."""
    mo2 = tmp_path / 'MO2'
    profile = mo2 / 'profiles' / 'Play'
    profile.mkdir(parents=True)
    (mo2 / 'mods').mkdir()
    ini = '[General]\nselected_profile=@ByteArray(Play)\n'
    if executables:
        ini += '[customExecutables]\nsize=1\n1\\title=F4SE\n1\\binary=C:/Games/Fallout 4/f4se_loader.exe\n'
    (mo2 / 'ModOrganizer.ini').write_text(ini, encoding='utf-8')
    (profile / 'modlist.txt').write_text(f'{HEADER}\n+Some Mod\n-F3NV - Fallout New Vegas\n', encoding='utf-8')
    (profile / 'plugins.txt').write_text('*Other.esp\nFalloutHelpers.esl\n', encoding='utf-8')
    return mo2


def _settings(tmp_path: Path, mo2: Path) -> dict:
    """Settings whose game output is a mod folder of `mo2`, holding the built game plugins."""
    s = S.defaults()
    s['games']['fallout4'] = str(tmp_path / 'fo4')
    s['work_dir'] = str(tmp_path / 'work')
    s['mod_sources'] = [{'folder': str(mo2), 'kind': 'mo2_profile', 'profile': ''}]
    out = mo2 / 'mods' / 'F3NV - Fallout New Vegas'
    out.mkdir()
    for name in ('FalloutNV.esm', 'FalloutHelpers.esl', 'CleanroomUI.esl'):
        (out / name).write_bytes(b'')
    s['per_source']['falloutnv']['output']['path'] = str(out)
    return s


def test_set_up_enables_the_mod_and_plugins_once(tmp_path):
    """The mod is enabled in place, plugins ticked or appended in order, lists backed up; a second run changes
    nothing."""
    mo2 = _instance(tmp_path)
    s = _settings(tmp_path, mo2)
    assert M.blocker(s, 'falloutnv', running=lambda: False) == ''
    assert M.blocker(s, 'falloutnv', running=lambda: True).startswith('Mod Organizer is running')
    changes = M.set_up(s, 'falloutnv')
    profile = mo2 / 'profiles' / 'Play'
    assert (profile / 'modlist.txt').read_text(encoding='utf-8').splitlines() == [
        HEADER, '+Some Mod', '+F3NV - Fallout New Vegas']
    assert (profile / 'plugins.txt').read_text(encoding='utf-8').splitlines() == [
        '*Other.esp', '*FalloutHelpers.esl', '*FalloutNV.esm', '*CleanroomUI.esl']
    assert (profile / 'loadorder.txt').read_text(encoding='utf-8').splitlines() == [
        'FalloutNV.esm', 'FalloutHelpers.esl', 'CleanroomUI.esl']
    assert (profile / ('modlist.txt' + M.BACKUP)).is_file() and len(changes) == 7
    assert M.set_up(s, 'falloutnv') == ['already set up']


def test_a_new_mod_goes_under_the_header(tmp_path):
    """A mod the list does not name is added enabled at the top, under MO2's header."""
    lines, notes = M.enable_mod([HEADER, '+Some Mod'], 'F3NV - Dead Money')
    assert lines == [HEADER, '+F3NV - Dead Money', '+Some Mod'] and notes == ['added and enabled F3NV - Dead Money']


def test_setup_needs_the_output_in_the_instance(tmp_path):
    """An output outside the instance's mods folder, or no MO2 source, blocks setup with the reason."""
    mo2 = _instance(tmp_path)
    s = _settings(tmp_path, mo2)
    s['per_source']['falloutnv']['output']['path'] = str(tmp_path / 'elsewhere')
    assert 'is not a mod folder of' in M.blocker(s, 'falloutnv', running=lambda: False)
    s['mod_sources'] = []
    assert M.blocker(s, 'falloutnv', running=lambda: False).startswith('no MO2 instance')


def test_play_runs_f4se_through_mo2_or_the_game(tmp_path):
    """Play runs MO2's F4SE executable for the profile; without MO2, the game's f4se_loader.exe."""
    mo2 = _instance(tmp_path)
    s = _settings(tmp_path, mo2)
    argv, where = M.play_command(s)
    assert argv == (str(mo2 / 'ModOrganizer.exe'), '-p', 'Play', 'run', '-e', 'F4SE') and where == str(mo2)
    s['mod_sources'] = []
    assert M.play_command(s) == ((), 'no f4se_loader.exe in the Fallout 4 folder: install F4SE')
    (tmp_path / 'fo4').mkdir()
    (tmp_path / 'fo4' / 'f4se_loader.exe').write_bytes(b'')
    assert M.play_command(s) == ((str(tmp_path / 'fo4' / 'f4se_loader.exe'),), str(tmp_path / 'fo4'))
    assert M.environment(_settings(tmp_path / 'b', _instance(tmp_path / 'b'))) == {
        'F3NV_MO2': str(tmp_path / 'b' / 'MO2')}


def test_faces_and_runtime_stages(tmp_path):
    """Faces run the FaceGen step on the built plugin and need MO2; the F4SE plugin is the game's own stage."""
    s = _settings(tmp_path, _instance(tmp_path))
    out = S.output_dir(s, 'falloutnv')
    faces = ST.command(s, 'falloutnv', 'faces', ST.Scope(), tmp_path / 'x.json')
    assert faces[1:3] == ['-m', 'fo4_import.spike.facegen'] and faces[-1] == 'FalloutNV.esm'
    assert faces[faces.index('--data') + 1] == str(out)
    assert ST.command(s, 'falloutnv', 'runtime', ST.Scope(), tmp_path / 'x.json')[-1] == str(out)
    assert 'runtime' in ST.GAME_ONLY and ST.unavailable(s, 'falloutnv', 'runtime') == ''
    s['mod_sources'] = []
    assert 'through MO2' in ST.unavailable(s, 'falloutnv', 'faces', platform='win32')


def test_runtime_dll_is_installed_into_f4se_plugins(tmp_path):
    """The committed F3NV.dll lands in F4SE/Plugins of the output."""
    dll = tmp_path / 'F3NV.dll'
    dll.write_bytes(b'dll')
    assert runtime_dll.install(tmp_path / 'out', dll).read_bytes() == b'dll'
    assert (tmp_path / 'out' / 'F4SE' / 'Plugins' / 'F3NV.dll').is_file()


def test_runner_passes_its_environment():
    """A stage sees the runner's extra environment (the Creation Kit's MO2 instance)."""
    lines = []
    plan = [('x', 'X', [sys.executable, '-c', 'import os; print(os.environ["F3NV_MO2"])'])]
    Runner(plan, {'F3NV_MO2': 'here'}).run(lines.append)
    assert 'here' in lines


def test_install_status_reads_the_app_settings(tmp_path):
    """The install check reads the app settings: MO2 source and work folder."""
    mo2 = _instance(tmp_path)
    m = machine_from(_settings(tmp_path, mo2))
    assert m.mo2 == mo2 and m.work == tmp_path / 'work' and m.profile == ''
